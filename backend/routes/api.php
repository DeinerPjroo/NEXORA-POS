<?php

use App\Http\Controllers\AuthController;
use App\Http\Controllers\BranchController;
use App\Http\Controllers\CashController;
use App\Http\Controllers\CategoryController;
use App\Http\Controllers\OperationsController;
use App\Http\Controllers\OrderController;
use App\Http\Controllers\PaymentHistoryController;
use App\Http\Controllers\PaymentMethodController;
use App\Http\Controllers\PaymentReviewController;
use App\Http\Controllers\ProductController;
use App\Http\Controllers\ProductImageController;
use App\Http\Controllers\RoleController;
use App\Http\Controllers\SaleController;
use App\Http\Controllers\SalesSettingController;
use App\Http\Controllers\TaxProfileController;
use App\Http\Controllers\VariantController;
use App\Http\Controllers\WorkspaceController;
use Illuminate\Support\Facades\Route;

Route::prefix('v1')->group(function () {
    Route::post('auth/register', [AuthController::class, 'register'])->middleware('throttle:registration');
    Route::post('auth/login', [AuthController::class, 'login'])->middleware('throttle:login');
    Route::post('auth/forgot-password', [AuthController::class, 'forgot'])->middleware('throttle:recovery');
    Route::post('auth/reset-password', [AuthController::class, 'reset'])->middleware('throttle:recovery');
    Route::middleware(['auth:sanctum', 'tenant'])->group(function () {
        Route::get('auth/me', [AuthController::class, 'me']);
        Route::post('auth/logout', [AuthController::class, 'logout']);
        Route::get('auth/sessions', [AuthController::class, 'sessions']);
        Route::delete('auth/sessions', [AuthController::class, 'revokeSessions'])->middleware('throttle:recovery');
        Route::get('workspace/overview', [WorkspaceController::class, 'overview']);
        Route::get('operations/context', [OperationsController::class, 'context']);
        Route::get('payment-methods', [PaymentMethodController::class, 'index']);
        Route::get('tax-profiles', [TaxProfileController::class, 'index']);
        Route::post('tax-profiles', [TaxProfileController::class, 'store']);
        Route::put('tax-profiles/{taxProfile}', [TaxProfileController::class, 'update']);
        Route::post('payment-methods', [PaymentMethodController::class, 'store']);
        Route::put('payment-methods/{paymentMethod}', [PaymentMethodController::class, 'update']);
        Route::get('sales/settings', [SalesSettingController::class, 'show']);
        Route::get('finance/payments', [PaymentHistoryController::class, 'index']);
        Route::get('finance/payments/{payment}/reviews', [PaymentReviewController::class, 'index']);
        Route::post('finance/payments/{payment}/reviews', [PaymentReviewController::class, 'store']);
        Route::put('sales/settings', [SalesSettingController::class, 'update']);
        Route::get('sales/cash-context', [SaleController::class, 'cashContext']);
        Route::get('sales', [SaleController::class, 'index']);
        Route::get('sales/{sale}', [SaleController::class, 'show']);
        Route::get('orders/{order}/quote', [SaleController::class, 'quote'])->name('sales.quote');
        Route::post('orders/{order}/collect', [SaleController::class, 'collect']);
        Route::post('sales/{sale}/refund', [SaleController::class, 'refund'])->name('sales.refund');
        Route::post('sales/{sale}/refunds', [SaleController::class, 'partialRefund']);
        Route::post('sales/{sale}/payments', [SaleController::class, 'addPayments']);
        Route::get('cash/registers', [CashController::class, 'registers']);
        Route::post('cash/registers', [CashController::class, 'storeRegister'])->name('cash.registers.store');
        Route::post('cash/registers/{cashRegister}/open', [CashController::class, 'open'])->name('cash.sessions.open');
        Route::get('cash/sessions', [CashController::class, 'sessions']);
        Route::get('cash/sessions/{cashSession}', [CashController::class, 'show']);
        Route::get('cash/sessions/{cashSession}/movements', [CashController::class, 'movements']);
        Route::post('cash/sessions/{cashSession}/movements', [CashController::class, 'move'])->name('cash.movements.store');
        Route::post('cash/sessions/{cashSession}/close', [CashController::class, 'close'])->name('cash.sessions.close');
        Route::get('orders', [OrderController::class, 'index']);
        Route::get('orders/{order}', [OrderController::class, 'show']);
        Route::post('orders', [OrderController::class, 'store']);
        Route::post('orders/{order}/status', [OrderController::class, 'changeState']);
        Route::get('workspace/team', [WorkspaceController::class, 'team']);
        Route::get('workspace/company', [WorkspaceController::class, 'settings']);
        Route::put('workspace/company', [WorkspaceController::class, 'updateCompany']);
        Route::get('workspace/theme', [WorkspaceController::class, 'theme']);
        Route::put('workspace/theme', [WorkspaceController::class, 'publishTheme']);
        Route::get('branches', [BranchController::class, 'index']);
        Route::post('branches', [BranchController::class, 'store']);
        Route::put('branches/{branch}', [BranchController::class, 'update']);
        Route::get('roles', [RoleController::class, 'index']);
        Route::post('roles', [RoleController::class, 'store']);
        Route::put('roles/{role}', [RoleController::class, 'update']);
        Route::get('categories', [CategoryController::class, 'index']);
        Route::post('categories', [CategoryController::class, 'store']);
        Route::put('categories/{category}', [CategoryController::class, 'update']);
        Route::get('products', [ProductController::class, 'index']);
        Route::get('products/{product}', [ProductController::class, 'show']);
        Route::post('products', [ProductController::class, 'store']);
        Route::put('products/{product}', [ProductController::class, 'update']);
        Route::get('products/{product}/image', [ProductImageController::class, 'show']);
        Route::post('products/{product}/image', [ProductImageController::class, 'store'])->middleware('throttle:uploads');
        Route::delete('products/{product}/image', [ProductImageController::class, 'destroy']);
        Route::scopeBindings()->group(function () {
            Route::get('products/{product}/variants', [VariantController::class, 'index']);
            Route::post('products/{product}/variants', [VariantController::class, 'store']);
            Route::put('products/{product}/variants/{variant}', [VariantController::class, 'update']);
        });
    });
});
